// Exports P9s's certificates, found by the untrusted search, as Lean data
// for the verified checker (dossier §15.8): research/composition-proofs/
// Composition/Sig/CheckData.lean, generated, not edited by hand. Each
// problem P9s accepts becomes a `SigProblem String String` and a
// certificate table, one entry per consistent pattern. Lean's
// `checkAll` then decides, independently, whether to believe it.
// Deliberate certificates (deliberate.mjs) replace the search's for
// their pattern; the source-level programs P9s accepts
// (source-boundary.mjs) are exported as `src-*`.
// Run: node export-lean.mjs [count] [seed]
import { writeFileSync } from 'node:fs'
import { witnesses, p9s } from './p9s.mjs'
import { parse } from './interpret.mjs'
import { generator } from './grammar.mjs'
import { CHALLENGES } from './challenges.mjs'
import { DELIBERATE } from './deliberate.mjs'
import { SOURCE } from './source-boundary.mjs'

const count = Number(process.argv[2] ?? 100)
const seed = Number(process.argv[3] ?? 7)
const OUT = new URL(
  '../../composition-proofs/Composition/Sig/CheckData.lean', import.meta.url)
const str = (s) => JSON.stringify(s)
const list = (xs) => `[${xs.join(', ')}]`

function texpr(t) {
  if (t.k === 'b') return `(.base ${str(t.b)})`
  if (t.k === 'v') return `(.tvar ${t.n})`
  if (t.k === 'f') return `(.arrow ${texpr(t.a)} ${texpr(t.c)})`
  const fields = t.fields.reduceRight(
    (acc, [l, ft]) => `(.cons ${str(l)} ${texpr(ft)} ${acc})`, '.nil')
  return `(.record ${fields} ${list(t.tails.map(String))})`
}

function atom(a) {
  if (a[0] === 'eq') return `.eq ${texpr(a[1])} ${texpr(a[2])}`
  if (a[0] === 'lacks') return `.lacks ${a[1]} ${str(a[2])}`
  if (a[0] === 'disjoint') return `.disjoint ${a[1]} ${a[2]}`
  return '.ff'
}

function problem(P) {
  return `⟨${list(P.rigidTys.map(String))}, ` +
    `${list(P.rigidRows.map(String))}, ${list(P.D.map(atom))}, ` +
    `${list(P.B.map(atom))}⟩`
}

function base(b) {
  let m = /^A(\d+)(.+)$/.exec(b)
  if (m) return `(.base (.inr (.A ${m[1]} ${str(m[2])})))`
  m = /^R(\d+)$/.exec(b)
  if (m) return `(.base (.inr (.R ${m[1]})))`
  m = /^T(\d+)$/.exec(b)
  if (m) return `(.base (.inr (.T ${m[1]})))`
  return `(.base (.inl ${str(b)}))`
}

function label(l) {
  return l.startsWith('ρ') ? `.inr ${l.slice(1)}` : `.inl ${str(l)}`
}

function sg(v) {
  if (v.k === 'b') return base(v.b)
  if (v.k === 'f') return `(.arrow ${sg(v.a)} ${sg(v.c)})`
  return `(.record ${entries(v.fields)})`
}

function entries(fields) {
  return list(fields.map(([l, v]) => `(${label(l)}, ${sg(v)})`))
}

function cert(flex) {
  const tys = []
  const rows = []
  for (const [k, g] of flex) {
    const n = Number(k.slice(1))
    if (k[0] === 't') tys.push(`(${n}, ${sg(parse(g))})`)
    else {
      const fields = Object.entries(g).map(([l, x]) => [l, parse(x)])
      rows.push(`(${n}, ${entries(fields)})`)
    }
  }
  return `⟨${list(tys)}, ${list(rows)}⟩`
}

function pattern(P, w) {
  return list(P.rigidRows.flatMap((r) => w.labels.filter((l) => w.present(r, l))
    .map((l) => `(${r}, ${str(l)})`)))
}

function table(P, override) {
  const out = []
  for (const w of witnesses(P)) {
    const flex = override?.pattern === w.pattern ? override.flex : w.flex
    if (flex === null) return null
    out.push(`(${pattern(P, w)}, ${cert(flex)})`)
  }
  return list(out)
}

const defs = []
function add(name, P, override) {
  const T = table(P, override)
  if (T === null) return
  defs.push({ name, P, T })
}

for (const [name, P] of CHALLENGES) add(name, P)
for (const [name, P, pat, flex] of DELIBERATE) {
  add(name, P, { pattern: pat, flex: new Map(Object.entries(flex)) })
}
for (const { name, P } of SOURCE) {
  if (p9s(P).verdict === 'valid') add(`src-${name}`, P)
}
const generate = generator(seed, false)
for (let i = 0; i < count; i++) {
  const P = generate()
  if (p9s(P).verdict === 'valid') add(`gen${i}`, P)
}

const ident = (name) => name.replace(/-/g, '_')
const body = defs.map(({ name, P, T }) =>
  `def ex_${ident(name)} : SigProblem String String :=\n  ${problem(P)}\n\n` +
  `def tab_${ident(name)} : CertTable String String :=\n  ${T}\n`).join('\n')
const all = list(defs.map(({ name }) =>
  `(${str(name)}, ex_${ident(name)}, tab_${ident(name)})`))
writeFileSync(OUT, `/-
GENERATED by research/composition-assessment/sig-oracle/export-lean.mjs
(\`node export-lean.mjs ${count} ${seed}\`); do not edit. Problems P9s's
untrusted search accepts, with the certificates it found (deliberate
ones for their patterns). CheckExamples.lean checks them with the
verified \`checkAll\`.
-/
import Composition.Sig.Patterns

namespace Composition.Syntax.CheckData

open Composition Composition.Syntax

${body}
def exported : List (String × SigProblem String String ×
    CertTable String String) :=
  ${all}

end Composition.Syntax.CheckData
`)
console.log(`${defs.length} problems exported`)
